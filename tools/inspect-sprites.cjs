/* Read PNG alpha for runtime framing; never changes generated image pixels. */
const fs=require('node:fs');
const path=require('node:path');
const zlib=require('node:zlib');
function inspect(buf,region) {
  let at=8,w,h,parts=[];
  while(at<buf.length) {
    const n=buf.readUInt32BE(at),type=buf.toString('ascii',at+4,at+8),data=buf.subarray(at+8,at+8+n);
    if(type==='IHDR'){w=data.readUInt32BE(0);h=data.readUInt32BE(4);if(data[8]!==8||data[9]!==6)throw Error('Expected RGBA8 PNG');}
    if(type==='IDAT')parts.push(data);at+=n+12;
  }
  const raw=zlib.inflateSync(Buffer.concat(parts)),stride=w*4,out=Buffer.alloc(stride*h);
  const paeth=(a,b,c)=>{const p=a+b-c,A=Math.abs(p-a),B=Math.abs(p-b),C=Math.abs(p-c);return A<=B&&A<=C?a:B<=C?b:c;};
  let k=0;
  for(let y=0;y<h;y++) {
    const filter=raw[k++];if(filter>4)throw Error('Invalid PNG filter');
    for(let x=0;x<stride;x++) {
      const i=y*stride+x,a=x>=4?out[i-4]:0,b=y?out[i-stride]:0,c=y&&x>=4?out[i-stride-4]:0;
      out[i]=(raw[k++]+(filter===0?0:filter===1?a:filter===2?b:filter===3?Math.floor((a+b)/2):paeth(a,b,c)))&255;
    }
  }
  const [left,top,right,bottom]=region?[
    Math.round(region.column*w/region.columns),Math.round(region.row*h/region.rows),
    Math.round((region.column+1)*w/region.columns),Math.round((region.row+1)*h/region.rows)
  ]:[0,0,w,h];
  const bounds=[right,bottom,left,top];let transparent=0;
  for(let y=top;y<bottom;y++)for(let x=left;x<right;x++) {
    const alpha=out[(y*w+x)*4+3];if(alpha===0)transparent++;
    if(alpha>8){bounds[0]=Math.min(bounds[0],x);bounds[1]=Math.min(bounds[1],y);bounds[2]=Math.max(bounds[2],x);bounds[3]=Math.max(bounds[3],y);}
  }
  if(transparent<(right-left)*(bottom-top)*.05)throw Error('Sprite is not a transparent cutout');
  let minFoot=w,maxFoot=0;
  for(let y=Math.floor(bounds[3]-(bounds[3]-bounds[1])*.075);y<=bounds[3];y++)for(let x=bounds[0];x<=bounds[2];x++)if(out[(y*w+x)*4+3]>128){minFoot=Math.min(minFoot,x);maxFoot=Math.max(maxFoot,x);}
  return {size:[w,h],box:[bounds[0],bounds[1],bounds[2]-bounds[0]+1,bounds[3]-bounds[1]+1],
    anchor:region?[region.column*w/region.columns+w/region.columns*.525,region.row*h/region.rows+h/region.rows*.95]:[Math.round((minFoot+maxFoot)/2),bounds[3]+1],
    ...(region?{referenceHeight:h/region.rows*.92,cell:[left,top,right-left,bottom-top]}:{}),transparentPixels:transparent};
}
const root=path.resolve(__dirname,'..'),manifest=JSON.parse(fs.readFileSync(path.join(root,'assets/q/provenance.json'))),specs={};
for(const item of manifest.assets) {
  const meta=inspect(fs.readFileSync(path.join(root,'assets/q',item.file)));
  specs[item.id]={src:`assets/q/${item.file}`,...meta};
  console.log(item.id,JSON.stringify(meta));
}
// A fixed cell scale/ground line preserves the run cycle's airborne poses.
const run=JSON.parse(fs.readFileSync(path.join(root,'assets/q/run-provenance.json')));
const sheet=fs.readFileSync(path.join(root,run.output));
for(let i=0;i<run.grid.frames;i++) {
  const meta=inspect(sheet,{column:i%run.grid.columns,row:Math.floor(i/run.grid.columns),...run.grid});
  specs[`heroRun${i}`]={src:run.output,...meta};
  console.log(`heroRun${i}`,JSON.stringify(meta));
}
fs.writeFileSync(path.join(root,'sprite-data.js'),`/* Generated by tools/inspect-sprites.cjs; original PNG pixels unchanged. */\n(() => {\n  const data=${JSON.stringify(specs,null,2)};\n  if(typeof module!=='undefined'&&module.exports)module.exports=data;else window.QSpriteData=data;\n})();\n`);
